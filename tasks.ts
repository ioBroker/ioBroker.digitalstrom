/*!
 * Build tasks of ioBroker.digitalstrom
 *
 *   npm run build           backend (src/ -> build/) and admin interface (src-admin/ -> admin/)
 *   npm run build:backend   the backend only
 *   npm run build:admin     the admin interface only
 *   npm run 0-clean         removes everything the build generates
 */
import { fork } from 'node:child_process';
import { existsSync } from 'node:fs';
import { buildReact, deleteFoldersRecursive } from '@iobroker/build-tools';

// tsx registers its loader through process.execArgv, and child_process.fork() hands that on.
// tsc and vite are plain JS and do not need it.
process.execArgv = [];

function cleanBackend(): void {
    deleteFoldersRecursive(`${__dirname}/build`);
}

function cleanAdmin(): void {
    // The icon is a source file, everything else in admin/ is generated by vite
    deleteFoldersRecursive(`${__dirname}/admin`, ['digitalstrom.png']);
}

/** Compiles the adapter: src/*.ts => build/*.js */
function buildBackend(): Promise<void> {
    cleanBackend();
    return new Promise((resolve, reject) => {
        const script = `${__dirname}/node_modules/typescript/bin/tsc`;
        if (!existsSync(script)) {
            reject(new Error(`Cannot find execution file: ${script}`));
            return;
        }
        const child = fork(script, ['-p', `${__dirname}/tsconfig.build.json`], { stdio: 'pipe', cwd: __dirname });
        child.stdout?.on('data', (data: Buffer) => console.log(data.toString()));
        child.stderr?.on('data', (data: Buffer) => console.error(data.toString()));
        child.on('close', code => (code ? reject(new Error(`tsc exit code: ${code}`)) : resolve()));
    });
}

/** Builds the React admin interface: src-admin/ => admin/index.html + admin/assets/ */
async function buildAdmin(): Promise<void> {
    cleanAdmin();
    // The dependencies of the admin interface are devDependencies of the adapter itself,
    // so there is no separate npm install in src-admin/
    await buildReact(`${__dirname}/src-admin/`, { rootDir: __dirname, vite: true });
}

function fail(e: unknown): void {
    console.error(`Cannot build: ${e as string}`);
    process.exit(1);
}

if (process.argv.includes('--0-clean')) {
    cleanBackend();
    cleanAdmin();
} else if (process.argv.includes('--backend')) {
    buildBackend().catch(fail);
} else if (process.argv.includes('--admin')) {
    buildAdmin().catch(fail);
} else {
    buildBackend()
        .then(() => buildAdmin())
        .catch(fail);
}
